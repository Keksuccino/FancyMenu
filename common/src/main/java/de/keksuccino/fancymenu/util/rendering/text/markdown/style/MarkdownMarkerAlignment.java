package de.keksuccino.fancymenu.util.rendering.text.markdown.style;

/**
 * Where the marker of a list item stands vertically.
 */
public enum MarkdownMarkerAlignment {

    /** In the middle of the height of the line. */
    LINE_CENTER,
    /** In the middle of the lowercase letters of the line, between the baseline and the top of a letter like "x". */
    X_HEIGHT

}
