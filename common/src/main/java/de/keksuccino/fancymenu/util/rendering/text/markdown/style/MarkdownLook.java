package de.keksuccino.fancymenu.util.rendering.text.markdown.style;

/**
 * A named bundle of values for all options of a {@link MarkdownStyle}.
 */
public enum MarkdownLook {

    /** The look Markdown text has by default: white text on gray panels and gray lines. */
    CLASSIC,
    /** Pixel art made for the Minecraft font: warm colors, gold ornaments, dithered lines and markers drawn pixel by pixel. */
    PIXEL,
    /** A plain look in the colors of the UI theme of FancyMenu, made for the smooth UI font. */
    NEUTRAL

}
