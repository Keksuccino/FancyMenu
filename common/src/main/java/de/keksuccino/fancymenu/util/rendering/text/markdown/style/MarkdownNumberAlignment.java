package de.keksuccino.fancymenu.util.rendering.text.markdown.style;

/**
 * Where the numbers of numbered list items stand in the space in front of the text of their items.
 */
public enum MarkdownNumberAlignment {

    /** At the start of that space, where the markers of other items of the list level start. Numbers of different lengths start below each other. */
    LEFT,
    /** At the end of that space, next to the text. Numbers of different lengths end below each other. */
    RIGHT

}
