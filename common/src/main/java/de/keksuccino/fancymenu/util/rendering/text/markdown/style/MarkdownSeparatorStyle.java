package de.keksuccino.fancymenu.util.rendering.text.markdown.style;

/**
 * What a separator ("---") looks like.
 */
public enum MarkdownSeparatorStyle {

    /** A line from one edge of the text area to the other. */
    LINE,
    /** An ornament in the middle of the text area, with a line on each side of it. The lines can fade out through dithering. */
    ORNAMENT

}
